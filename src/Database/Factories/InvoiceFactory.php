<?php

declare(strict_types=1);

namespace AichaDigital\Larabill\Database\Factories;

use AichaDigital\Lara100\ValueObjects\FixedDecimal;
use AichaDigital\Larabill\Enums\FiscalSubmissionStatus;
use AichaDigital\Larabill\Enums\InvoiceDocumentStatus;
use AichaDigital\Larabill\Enums\InvoiceSerieType;
use AichaDigital\Larabill\Enums\InvoiceStatus;
use AichaDigital\Larabill\Models\Invoice;
use Illuminate\Database\Eloquent\Factories\Factory;

/**
 * Invoice Factory
 *
 * v0.3.3: Updated for fiscal compliance
 * Uses integer base 100 for monetary values (amounts, prices)
 * Example: €12.34 is stored as 1234, €1.00 as 100
 *
 * @extends Factory<Invoice>
 *
 * @internal Implementation detail — may change without a major version (AID-413).
 */
class InvoiceFactory extends Factory
{
    protected $model = Invoice::class;

    public function definition(): array
    {
        $taxableAmount = $this->faker->numberBetween(1000, 100000); // €10.00 to €1000.00 in base 100
        $taxAmount     = (int) ($taxableAmount * 0.21); // 21% tax in base 100
        $totalAmount   = $taxableAmount + $taxAmount;
        $currentYear   = now()->year;

        return [
            // v0.3.3: New fiscal numbering fields
            'fiscal_number' => 'FAC-'.$currentYear.'-'.$this->faker->unique()->numerify('######'),
            'prefix'        => 'FAC',
            'serie'         => InvoiceSerieType::INVOICE->value,
            'series_number' => $this->faker->unique()->numberBetween(1, 999999),
            'fiscal_year'   => $currentYear,

            // v0.3.3: Date fields
            'invoice_date' => $this->faker->dateTimeBetween('-30 days', 'now'),
            'issued_at'    => $this->faker->dateTimeBetween('-30 days', 'now'),
            'service_date' => $this->faker->optional(0.3)->dateTimeBetween('-60 days', 'now'),
            'due_date'     => $this->faker->optional(0.8)->dateTimeBetween('now', '+30 days'),
            'paid_at'      => $this->faker->optional(0.3)->dateTimeBetween('-30 days', 'now'),

            // v0.3.3: Status using enum — AID-1688: DETERMINISTIC, never a
            // dice roll (AID-558/AID-581 discipline, same class as the
            // is_roi_taxed de-randomization). The default row IS the issued
            // fiscal shape, so the default collection status is SENT —
            // "issued and in collection". A test that needs another
            // collection status declares it (draft()/sent()/paid()/
            // overdue() states) or overrides it inline; it never inherits
            // one from the factory's coin.
            'status'  => InvoiceStatus::SENT->value,

            // ADR-016 §8.2/§8.5 (PR-1, AID-1627): a fiscal numbered fixture IS
            // the legacy/transitional shape — the number WAS consumed at birth
            // — so it stamps the document axis ISSUED with the backfill's
            // submission value. Both values are deterministic (AID-558
            // discipline): a test that needs another document state declares
            // it, never inherits it from a dice roll. A test creating a
            // PROFORMA row declares it with the proforma() state — the §8.2
            // enforcer rejects both the unstamped fiscal shape and the
            // stamped proforma shape.
            'invoice_document_status'  => InvoiceDocumentStatus::ISSUED->value,
            'fiscal_submission_status' => FiscalSubmissionStatus::LEGACY_UNKNOWN->value,
            'document_cancelled_at'    => null,
            'document_cancelled_by'    => null,

            // Relations (ADR-001 + ADR-003: CompanyFiscalConfig + UserTaxProfile architecture)
            'user_id'                   => null, // Owner of invoice (issuer)
            'billable_user_id'          => null, // User being billed (ADR-003 replaces customer_id)
            'company_fiscal_config_id'  => null,
            'user_tax_profile_id'       => null,
            'proforma_id'               => null,
            'rectifies_invoice_id'      => null,

            // Encrypted snapshots (generated by InvoiceService at creation)
            'issuer_snapshot'   => null,
            'customer_snapshot' => null,
            'fiscal_snapshot'   => null,
            // Reverse charge: deterministic false default (AID-576, same class
            // as the AID-558 is_immutable coin). The old 10% random default fed
            // DomPDFService::resolveTemplateType(), so ~10% of fiscal fixtures
            // silently resolved as reverse-charge and rendered the conformant
            // package blade — flaking any guard that assumes a plain FISCAL
            // invoice. A test that needs reverse charge states it (is_roi_taxed
            // => true), never inherits it from a dice roll.
            'is_roi_taxed'      => false,

            // v0.3.3: Renamed amount fields
            'taxable_amount'   => FixedDecimal::ofUnscaled($taxableAmount, 2),
            'total_tax_amount' => FixedDecimal::ofUnscaled($taxAmount, 2),
            'total_amount'     => FixedDecimal::ofUnscaled($totalAmount, 2),

            // Immutability: deterministic mutable default (AID-558). The old
            // 20% random coin made any fixture that later edits the invoice or
            // its lines flaky once the immutability guards existed — a test
            // that needs a frozen invoice states it (makeImmutable() or an
            // explicit override), never inherits it from a dice roll.
            'is_immutable' => false,
            'immutable_at' => null,

            // Additional fields
            'notes'         => $this->faker->optional()->sentence(),
            'payment_terms' => $this->faker->optional()->randomElement(['Net 30', 'Net 60', 'Due on receipt']),
            'template_name' => $this->faker->optional()->randomElement(['default', 'modern', 'classic']),
        ];
    }

    /**
     * Create a paid invoice
     */
    public function paid(): static
    {
        return $this->state(function (array $attributes) {
            return [
                'status'  => InvoiceStatus::PAID->value,
                'paid_at' => $this->faker->dateTimeBetween('-30 days', 'now'),
            ];
        });
    }

    /**
     * Create an overdue invoice
     */
    public function overdue(): static
    {
        return $this->state(function (array $attributes) {
            return [
                'status'   => InvoiceStatus::OVERDUE->value,
                'due_date' => $this->faker->dateTimeBetween('-30 days', '-1 day'),
                'paid_at'  => null,
            ];
        });
    }

    /**
     * Create a draft invoice
     */
    public function draft(): static
    {
        return $this->state(function (array $attributes) {
            return [
                'status'   => InvoiceStatus::DRAFT->value,
                'paid_at'  => null,
                'due_date' => null,
            ];
        });
    }

    /**
     * Create a sent invoice
     */
    public function sent(): static
    {
        return $this->state(function (array $attributes) {
            return [
                'status' => InvoiceStatus::SENT->value,
            ];
        });
    }

    /**
     * Create an unissued fiscal draft (ADR-016 §7.1 phase 1, AID-1688).
     *
     * The durable, unnumbered DRAFT that `createInvoice(status: 'draft')`
     * births: the five number/issuance fields are all NULL (§8.2 C4), the
     * document axis is DRAFT and the collection axis is DRAFT. The prefix
     * stays stamped (§8.1) — only the number waits for `issue()`.
     */
    public function unissuedDraft(): static
    {
        return $this->state(function (array $attributes) {
            return [
                'fiscal_number'            => null,
                'series_number'            => null,
                'fiscal_year'              => null,
                'invoice_date'             => null,
                'issued_at'                => null,
                'invoice_document_status'  => InvoiceDocumentStatus::DRAFT->value,
                'fiscal_submission_status' => null,
                'status'                   => InvoiceStatus::DRAFT->value,
                'paid_at'                  => null,
                'due_date'                 => null,
            ];
        });
    }

    /**
     * Create a conversion-born PREPARED row (ADR-016 §5.2, AID-1688).
     *
     * The verbatim proforma clone waiting for `issue()`: document axis
     * PREPARED, the five number/issuance fields all NULL, collection axis
     * DRAFT, and the link back to the proforma it was born from. The serie
     * stays the fiscal default (the conversion target) — the §8.2 C2
     * biconditional requires a non-NULL axis only on fiscal rows.
     */
    public function prepared(Invoice $proforma): static
    {
        return $this->state(function (array $attributes) use ($proforma) {
            return [
                'fiscal_number'            => null,
                'series_number'            => null,
                'fiscal_year'              => null,
                'invoice_date'             => null,
                'issued_at'                => null,
                'invoice_document_status'  => InvoiceDocumentStatus::PREPARED->value,
                'fiscal_submission_status' => null,
                'status'                   => InvoiceStatus::DRAFT->value,
                'paid_at'                  => null,
                'due_date'                 => null,
                'proforma_id'              => $proforma->id,
            ];
        });
    }

    /**
     * Create a draft cancelled before issuance (ADR-016 §5.1, AID-1688).
     *
     * Terminal on the document axis and never numbered: CANCELLED with its
     * cancellation instant (§8.2 C5) and no actor (S4-r is one-directional:
     * the instant is mandatory, the actor is optional), five issuance fields
     * NULL, submission axis NULL and the collection axis moved to CANCELLED
     * with it.
     */
    public function cancelledBeforeIssue(): static
    {
        return $this->state(function (array $attributes) {
            return [
                'fiscal_number'            => null,
                'series_number'            => null,
                'fiscal_year'              => null,
                'invoice_date'             => null,
                'issued_at'                => null,
                'invoice_document_status'  => InvoiceDocumentStatus::CANCELLED->value,
                'fiscal_submission_status' => null,
                'document_cancelled_at'    => now(),
                'document_cancelled_by'    => null,
                'status'                   => InvoiceStatus::CANCELLED->value,
                'paid_at'                  => null,
                'due_date'                 => null,
            ];
        });
    }

    /**
     * Create an immutable invoice
     */
    public function immutable(): static
    {
        return $this->state(function (array $attributes) {
            return [
                'is_immutable' => true,
                'immutable_at' => $this->faker->dateTimeBetween('-30 days', 'now'),
            ];
        });
    }

    /**
     * Create a proforma invoice
     */
    public function proforma(): static
    {
        return $this->state(function (array $attributes) {
            $currentYear = now()->year;

            return [
                'fiscal_number' => 'PRO-'.$currentYear.'-'.$this->faker->unique()->numerify('######'),
                'prefix'        => 'PRO',
                'serie'         => InvoiceSerieType::PROFORMA->value,
                'status'        => InvoiceStatus::DRAFT->value,
                // ADR-016 §8.2: the document axis does not exist on proforma
                // rows — both lifecycle axes explicitly NULL (the §8.2 CHECK
                // biconditional requires it; stating it makes the fixture's
                // shape explicit instead of incidental).
                'invoice_document_status'  => null,
                'fiscal_submission_status' => null,
            ];
        });
    }

    /**
     * Create a rectificative invoice
     */
    public function rectificative(): static
    {
        return $this->state(function (array $attributes) {
            $currentYear = now()->year;

            return [
                'fiscal_number' => 'RECT-'.$currentYear.'-'.$this->faker->unique()->numerify('######'),
                'prefix'        => 'RECT',
                'serie'         => InvoiceSerieType::RECTIFICATIVE->value,
            ];
        });
    }

    /**
     * Create a credit invoice (negative amounts for rectificative)
     */
    public function credit(): static
    {
        return $this->state(function (array $attributes) {
            $taxableAmount = -$this->faker->numberBetween(1000, 10000); // Negative amount
            $taxAmount     = (int) ($taxableAmount * 0.21);
            $totalAmount   = $taxableAmount + $taxAmount;
            $currentYear   = now()->year;

            return [
                'fiscal_number'    => 'RECT-'.$currentYear.'-'.$this->faker->unique()->numerify('######'),
                'prefix'           => 'RECT',
                'serie'            => InvoiceSerieType::RECTIFICATIVE->value,
                'taxable_amount'   => FixedDecimal::ofUnscaled($taxableAmount, 2),
                'total_tax_amount' => FixedDecimal::ofUnscaled($taxAmount, 2),
                'total_amount'     => FixedDecimal::ofUnscaled($totalAmount, 2),
            ];
        });
    }
}
